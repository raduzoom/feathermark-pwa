// The design system for the web app: turns universal/design/tokens.json into CSS custom properties
// (src/ui/tokens.css), the web's layout sizes (layout.web) included, and checks that the stylesheets use them.
// Run: pnpm design-system           writes tokens.css, then checks
//      pnpm design-system --check   checks only (scripts/test_all.sh); exits 1 on any problem
// The checks: tokens.css matches tokens.json; no colour literal outside tokens.css; every var(--x) is defined; no
// layout.web size written as raw px (mark a coincidence "/* design-system: not a layout size */"); every @media
// width is a layout.web breakpoint.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const OUTPUT = fileURLToPath(new URL('../src/ui/tokens.css', import.meta.url))
const HEADER = '/* Generated by scripts/design-system.ts from universal/design/tokens.json. Do not edit. */'
const FONTS: Record<string, string> = {
  serif: "ui-serif, 'New York', 'Sitka Text', Georgia, 'Noto Serif', serif",
  sans: "system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  mono: "ui-monospace, 'SF Mono', 'Cascadia Mono', Menlo, 'Roboto Mono', monospace",
}
const IGNORED = new Set(['use', 'macos', 'windows', 'ios', 'android', 'all', 'note'])
const COLOUR = /^(#[0-9a-f]{3,8}|rgba?\([^)]*\))$/i

/** FEATHER_TOKENS, else ../universal/design/tokens.json beside this repo. */
export function tokensPath(): string {
  const path = process.env.FEATHER_TOKENS ?? fileURLToPath(new URL('../../universal/design/tokens.json', import.meta.url))
  if (!existsSync(path)) throw new Error(`tokens.json not found at ${path} (set FEATHER_TOKENS)`)
  return path
}

const kebab = (name: string) => name.replace(/\./g, '-').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

type Json = Record<string, unknown>

export function tokensToCss(tokens: unknown): string {
  const t = tokens as Json
  const light: string[] = []
  const dark: string[] = []
  const put = (list: string[], name: string, value: string) => list.push(`  --${name}: ${value};`)

  for (const [key, entry] of Object.entries(t.color as Json)) {
    const base = `c-${kebab(key)}`
    for (const [field, value] of Object.entries(entry as Json)) {
      if (IGNORED.has(field)) continue
      const mode = /^(.*?)\.?(light|dark)$/.exec(field)
      if (mode) {
        const list = mode[2] === 'light' ? light : dark
        const name = mode[1] ? `${base}-${kebab(mode[1])}` : base
        if (Array.isArray(value)) value.forEach((v, i) => put(list, `${name}-${i + 1}`, String(v)))
        else if (typeof value === 'string' && COLOUR.test(value)) put(list, name, value)
      } else if (typeof value === 'string' && COLOUR.test(value)) {
        put(light, `${base}-${kebab(field)}`, value)
      }
    }
  }

  for (const [name, stack] of Object.entries(FONTS)) put(light, `font-${name}`, stack)

  for (const [key, spec] of Object.entries(t.type as Json)) {
    const s = spec as Json
    const name = `type-${kebab(key)}`
    if (typeof s.desktop === 'number') put(light, `${name}-size`, `${s.desktop}px`)
    if (typeof s.lineHeight === 'number') put(light, `${name}-line`, String(s.lineHeight))
    if (typeof s.weight === 'number') put(light, `${name}-weight`, String(s.weight))
    if (typeof s.tracking === 'number') put(light, `${name}-tracking`, `${s.tracking}px`)
  }

  for (const n of (t.spacing as Json).scale as number[]) put(light, `space-${n}`, `${n}px`)

  for (const [key, value] of Object.entries(t.radius as Json)) {
    if (/windows|macos/.test(key)) continue
    put(light, `radius-${kebab(key)}`, value === 'full' ? '999px' : `${value}px`)
  }

  for (const [key, value] of Object.entries(t.controlHeight as Json)) put(light, `h-${kebab(key)}`, `${value}px`)

  for (const size of layoutSizes(t)) put(light, size.name, `${size.px}px`)

  for (const [key, value] of Object.entries(t.appIcon as Json)) {
    if (typeof value === 'string' && COLOUR.test(value)) put(light, `icon-${kebab(key)}`, value)
  }

  return `${HEADER}\n:root {\n${light.join('\n')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n${dark.map((l) => '  ' + l).join('\n')}\n  }\n}\n`
}

// layout.web: every number is a size (rows, widths, gaps, radii), but the breakpoints, which CSS can't take from a
// variable, are checked against the @media rules instead.
const BREAKPOINTS = new Set(['threeColumnsFrom', 'drawerFrom'])

type LayoutSize = { path: string; name: string; px: number }

function layoutSizes(t: Json): LayoutSize[] {
  const web = (t.layout as Json | undefined)?.web as Json | undefined
  const out: LayoutSize[] = []
  const walk = (o: Json, path: string[]) => {
    for (const [key, value] of Object.entries(o)) {
      const at = [...path, key]
      if (typeof value === 'number' && !(path.length === 0 && BREAKPOINTS.has(key)))
        out.push({ path: at.join('.'), name: `layout-${at.map(kebab).join('-')}`, px: value })
      else if (value && typeof value === 'object' && !Array.isArray(value)) walk(value as Json, at)
    }
  }
  if (web) walk(web, [])
  return out
}

export type Sheet = { file: string; text: string }
export type Rule = 'tokens' | 'colour' | 'variable' | 'layout' | 'breakpoint'
export type Problem = { rule: Rule; file: string; line: number; message: string }

const ALLOW_SIZE = 'design-system: not a layout size'

/** Every problem in the stylesheets, in file and line order (see the file's top comment for the rules). */
export function checkDesignSystem({ tokens, tokensCss, sheets }: { tokens: unknown; tokensCss: string; sheets: Sheet[] }): Problem[] {
  const t = tokens as Json
  const problems: Problem[] = []
  if (tokensCss !== tokensToCss(t))
    problems.push({ rule: 'tokens', file: 'src/ui/tokens.css', line: 1, message: 'tokens.css does not match tokens.json: run pnpm design-system' })

  const defined = new Set<string>()
  for (const text of [tokensCss, ...sheets.map((s) => s.text)]) for (const m of text.matchAll(/(--[\w-]+)\s*:/g)) defined.add(m[1]!)

  // a layout size another token shares (16 = space-16, 40 = h-button-large) is just a size; the rest are layout's own
  const shared = new Set<number>()
  const other = /^\s*--(space|radius|h|type)-[\w-]+:\s*(\d+(?:\.\d+)?)px;/gm
  for (const m of tokensToCss({ ...t, layout: undefined }).matchAll(other)) shared.add(Number(m[2]))
  const layout = new Map<number, LayoutSize>()
  for (const size of layoutSizes(t)) if (!shared.has(size.px) && !layout.has(size.px)) layout.set(size.px, size)

  const web = ((t.layout as Json | undefined)?.web ?? {}) as Json
  const from = Number(web.threeColumnsFrom)
  const drawer = Number(web.drawerFrom)
  const breakpoints = [from, from - 1, drawer - 1].filter((n) => Number.isFinite(n))

  for (const { file, text } of sheets) {
    if (file.endsWith('tokens.css')) continue
    const raw = text.split('\n')
    // comments blanked, line breaks kept, so line numbers hold
    const lines = text.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' ')).split('\n')
    lines.forEach((line, i) => {
      const at = (rule: Rule, message: string) => problems.push({ rule, file, line: i + 1, message })
      for (const m of line.matchAll(/#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(/g)) at('colour', `colour literal ${m[0]}: use a --c-* variable`)
      for (const m of line.matchAll(/var\((--[\w-]+)/g)) if (!defined.has(m[1]!)) at('variable', `var(${m[1]}) is not defined`)
      if (/@media/.test(line)) {
        for (const m of line.matchAll(/(?:min|max)-width:\s*(\d+)px/g))
          if (breakpoints.length && !breakpoints.includes(Number(m[1])))
            at('breakpoint', `breakpoint ${m[1]}px is not in layout.web (use ${breakpoints.join(', ').replace(/, (\d+)$/, ' or $1')})`)
        return
      }
      if (raw[i]!.includes(ALLOW_SIZE)) return
      for (const m of line.matchAll(/(?<![\w.-])(\d+(?:\.\d+)?)px/g)) {
        const size = layout.get(Number(m[1]))
        if (size) at('layout', `${m[1]}px is layout.web.${size.path}: use var(--${size.name})`)
      }
    })
  }
  return problems
}

/** The stylesheets under `dir`, with their paths as given. */
export function stylesheets(dir: string): Sheet[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? stylesheets(join(dir, e.name)) : e.name.endsWith('.css') ? [{ file: join(dir, e.name), text: readFileSync(join(dir, e.name), 'utf8') }] : [],
  )
}

const RULES: Array<[Rule, string]> = [
  ['tokens', 'tokens.css matches tokens.json'],
  ['colour', 'no colour literals outside tokens.css'],
  ['variable', 'every var() is defined'],
  ['layout', 'no layout.web size written as raw px'],
  ['breakpoint', 'every breakpoint comes from layout.web'],
]

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tokens = JSON.parse(readFileSync(tokensPath(), 'utf8'))
  if (!process.argv.includes('--check')) writeFileSync(OUTPUT, tokensToCss(tokens))
  const root = fileURLToPath(new URL('..', import.meta.url))
  const src = join(root, 'src')
  const problems = checkDesignSystem({ tokens, tokensCss: existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '', sheets: stylesheets(src) })
  for (const [rule, ok] of RULES) {
    const mine = problems.filter((p) => p.rule === rule)
    if (!mine.length) console.log(`✓ ${ok}`)
    for (const p of mine) console.log(`✗ ${relative(root, p.file)}:${p.line}  ${p.message}`)
  }
  if (problems.length) {
    console.log(`${problems.length} problem${problems.length === 1 ? '' : 's'}`)
    process.exit(1)
  }
}
