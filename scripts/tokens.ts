// Turns universal/design/tokens.json into CSS custom properties (src/ui/tokens.css).
// Run: node scripts/tokens.ts          writes the file
//      node scripts/tokens.ts --check  exits 1 if the file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const OUTPUT = fileURLToPath(new URL('../src/ui/tokens.css', import.meta.url))
const HEADER = '/* Generated by scripts/tokens.ts from universal/design/tokens.json. Do not edit. */'
const FONTS: Record<string, string> = {
  serif: "ui-serif, 'New York', 'Sitka Text', Georgia, 'Noto Serif', serif",
  sans: "system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  mono: "ui-monospace, 'SF Mono', 'Cascadia Mono', Menlo, 'Roboto Mono', monospace",
}
const IGNORED = new Set(['use', 'macos', 'windows', 'ios', 'android', 'all', 'note'])
const COLOUR = /^(#[0-9a-f]{3,8}|rgba?\([^)]*\))$/i

/** FEATHER_TOKENS, else ../universal/design/tokens.json beside this repo. */
export function tokensPath(): string {
  const path = process.env.FEATHER_TOKENS ?? fileURLToPath(new URL('../../universal/design/tokens.json', import.meta.url))
  if (!existsSync(path)) throw new Error(`tokens.json not found at ${path} (set FEATHER_TOKENS)`)
  return path
}

const kebab = (name: string) => name.replace(/\./g, '-').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

type Json = Record<string, unknown>

export function tokensToCss(tokens: unknown): string {
  const t = tokens as Json
  const light: string[] = []
  const dark: string[] = []
  const put = (list: string[], name: string, value: string) => list.push(`  --${name}: ${value};`)

  for (const [key, entry] of Object.entries(t.color as Json)) {
    const base = `c-${kebab(key)}`
    for (const [field, value] of Object.entries(entry as Json)) {
      if (IGNORED.has(field)) continue
      const mode = /^(.*?)\.?(light|dark)$/.exec(field)
      if (mode) {
        const list = mode[2] === 'light' ? light : dark
        const name = mode[1] ? `${base}-${kebab(mode[1])}` : base
        if (Array.isArray(value)) value.forEach((v, i) => put(list, `${name}-${i + 1}`, String(v)))
        else if (typeof value === 'string' && COLOUR.test(value)) put(list, name, value)
      } else if (typeof value === 'string' && COLOUR.test(value)) {
        put(light, `${base}-${kebab(field)}`, value)
      }
    }
  }

  for (const [name, stack] of Object.entries(FONTS)) put(light, `font-${name}`, stack)

  for (const [key, spec] of Object.entries(t.type as Json)) {
    const s = spec as Json
    const name = `type-${kebab(key)}`
    if (typeof s.desktop === 'number') put(light, `${name}-size`, `${s.desktop}px`)
    if (typeof s.lineHeight === 'number') put(light, `${name}-line`, String(s.lineHeight))
    if (typeof s.weight === 'number') put(light, `${name}-weight`, String(s.weight))
    if (typeof s.tracking === 'number') put(light, `${name}-tracking`, `${s.tracking}px`)
  }

  for (const n of (t.spacing as Json).scale as number[]) put(light, `space-${n}`, `${n}px`)

  for (const [key, value] of Object.entries(t.radius as Json)) {
    if (/windows|macos/.test(key)) continue
    put(light, `radius-${kebab(key)}`, value === 'full' ? '999px' : `${value}px`)
  }

  for (const [key, value] of Object.entries(t.controlHeight as Json)) put(light, `h-${kebab(key)}`, `${value}px`)

  for (const [key, value] of Object.entries(t.appIcon as Json)) {
    if (typeof value === 'string' && COLOUR.test(value)) put(light, `icon-${kebab(key)}`, value)
  }

  return `${HEADER}\n:root {\n${light.join('\n')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n${dark.map((l) => '  ' + l).join('\n')}\n  }\n}\n`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const css = tokensToCss(JSON.parse(readFileSync(tokensPath(), 'utf8')))
  if (process.argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
    if (current !== css) {
      console.error('tokens.css is stale')
      process.exit(1)
    }
  } else {
    writeFileSync(OUTPUT, css)
  }
}
