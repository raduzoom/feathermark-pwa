import type { Page } from '@playwright/test'
import { test, expect } from './fixtures'
import { noteMore } from './support/note-more'

const library = (page: Page) => page.getByRole('navigation', { name: 'Library' })
const list = (page: Page) => page.getByRole('listbox', { name: 'Notes' })

test('the demo line says notes aren’t saved and links to the download page', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText("This is a demo. Notes here aren't saved.")).toBeVisible()
  await expect(page.getByRole('link', { name: 'Get FeatherMark' })).toHaveAttribute('href', 'https://feathermark.com/download')
  // a new tab: following it in this one would end the demo and lose its notes
  await expect(page.getByRole('link', { name: 'Get FeatherMark' })).toHaveAttribute('target', '_blank')
  await expect(page.getByRole('link', { name: 'Get FeatherMark' })).toHaveAttribute('rel', 'noopener noreferrer')
  await expect(page.getByRole('button', { name: 'Log in' })).toHaveCount(0)
})

test('at phone width the list opens a note full width and Back returns', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('main')).toBeHidden()
  await list(page).getByRole('option', { name: /^Groceries/ }).click()
  await expect(page.getByRole('main')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Notes' })).toBeHidden()
  await expect(page.getByRole('textbox', { name: 'Title' })).toHaveValue('Groceries')
  const back = page.getByRole('button', { name: 'Back to notes' })
  expect((await back.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await back.click()
  await expect(page.getByRole('region', { name: 'Notes' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})

